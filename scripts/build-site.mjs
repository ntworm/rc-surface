function replaceSeo(html, block) {
  const start = html.indexOf(SEO_BEGIN);
  const end = html.indexOf(SEO_END);
  if (start < 0 || end < start) throw new Error('docs/index.html has lost its seo:begin / seo:end markers');
  return html.slice(0, start) + block + html.slice(end + SEO_END.length);
}

