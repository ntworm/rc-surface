/**
 * Builds the parts of the published site that search engines and AI crawlers
 * read, from the sources a person edits:
 *
 *   docs/index.html   the <head> block between the seo markers (title,
 *                     description, hreflang, Open Graph, JSON-LD)
 *   docs/pt-br.html   the Portuguese landing page as its own URL, with every
 *                     catalog string already in the markup
 *   docs/llms-full.txt the English README and reference docs in one file
 *   docs/sitemap.xml  both landing URLs with their hreflang pairing
 *
 * The landing page translates itself in the browser, which is enough for a
 * reader and not enough for a search engine: it indexes one URL per language,
 * and a crawler that does not click the PT button never sees Portuguese.
 *
 *   node scripts/build-site.mjs          write the files
 *   node scripts/build-site.mjs --check  exit 1 if any of them is stale
 */
