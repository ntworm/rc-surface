// ── sitemap.xml ────────────────────────────────────────────────────────────

function sitemap() {
  const alternates = [['en', META.en.url], ['pt-BR', META['pt-BR'].url], ['x-default', META.en.url]]
    .map(([lang, href]) => `    <xhtml:link rel="alternate" hreflang="${lang}" href="${href}"/>`)
    .join('\n');
  const urls = [META.en.url, META['pt-BR'].url]
    .map((loc) => `  <url>\n    <loc>${loc}</loc>\n${alternates}\n  </url>`)
    .join('\n');
  return '<?xml version="1.0" encoding="UTF-8"?>\n'
    + '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
    + urls + '\n</urlset>\n';
}

// ── main ───────────────────────────────────────────────────────────────────

export function buildSite() {
  const catalog = loadCatalog();
  const source = fs.readFileSync(path.join(docs, 'index.html'), 'utf8');
  // The FAQ in the English block is read from what the English catalog puts
  // on screen, not from the markup's fallback text.
  const en = replaceSeo(source, seoBlock('en', translateHtml(source, catalog, 'en')));

  let pt = translateHtml(en, catalog, 'pt-BR');
  pt = replaceSeo(pt, seoBlock('pt-BR', pt));
  pt = pt.replace('<html lang="en">', '<html lang="pt-BR" data-default-locale="pt-BR">');
  if (!pt.includes('data-default-locale="pt-BR"')) throw new Error('docs/index.html must open with <html lang="en">');

  return {
    'docs/index.html': en,
    ['docs/' + PT_FILE]: pt,
    'docs/llms-full.txt': llmsFull(),
    'docs/sitemap.xml': sitemap(),
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [rel, content] of Object.entries(buildSite())) {
    const file = path.join(root, rel);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === content) continue;
    stale.push(rel);
    if (!check) fs.writeFileSync(file, content);
  }
  if (check && stale.length) {
    console.error(`stale: ${stale.join(', ')} — run npm run build:site`);
    process.exit(1);
  }
  console.log(stale.length ? `${check ? 'stale' : 'wrote'}: ${stale.join(', ')}` : 'site files up to date');
}
