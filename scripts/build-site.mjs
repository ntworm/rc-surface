// ── catalog ────────────────────────────────────────────────────────────────

function loadCatalog() {
  const scope = {};
  vm.runInNewContext(fs.readFileSync(path.join(docs, 'site-i18n.js'), 'utf8'), { globalThis: scope });
  return scope.RcSurfaceSiteCatalog;
}

const escapeText = (value) => String(value)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escapeAttr = (value) => escapeText(value).replace(/"/g, '&quot;');

// ── HTML: apply the catalog the way i18n.js does, but ahead of time ────────

const VOID = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link',
  'meta', 'source', 'track', 'wbr']);
const RAW = new Set(['script', 'style']);
const ATTRIBUTE_HANDLES = [
  ['data-i18n-title', 'title'],
  ['data-i18n-placeholder', 'placeholder'],
  ['data-i18n-aria-label', 'aria-label'],
  ['data-i18n-href', 'href'],
];

function attr(attrs, name) {
  const m = attrs.match(new RegExp(`\\s${name}="([^"]*)"`));
  return m ? m[1] : null;
}

function setAttr(tag, name, value) {
  const re = new RegExp(`(\\s${name}=")[^"]*(")`);
  if (re.test(tag)) return tag.replace(re, (whole, a, b) => a + escapeAttr(value) + b);
  return tag.replace(/(\s*\/?>)$/, ` ${name}="${escapeAttr(value)}"$1`);
}

/**
 * i18n.js sets textContent for data-i18n and innerHTML for data-i18n-html.
 * An outer replacement discards whatever it contained, so only the outermost
 * handled element of any subtree is rewritten here — the same result the
 * browser reaches.
 */
function translateHtml(html, catalog, locale) {
  const bodyAt = html.indexOf('<body');
  const token = /<!--[\s\S]*?-->|<(\/?)([a-zA-Z][\w-]*)((?:"[^"]*"|'[^']*'|[^>"'])*)>/g;
  token.lastIndex = bodyAt;
  const stack = [];
  const inner = [];   // [start, end, replacement]
  const tags = [];    // [start, end, replacement] for attribute handles
  let m;
  while ((m = token.exec(html))) {
    if (m[0].startsWith('<!--')) continue;
    const closing = m[1] === '/';
    const name = m[2].toLowerCase();
    const attrs = m[3];
    if (closing) {
      for (let i = stack.length - 1; i >= 0; i--) {
        if (stack[i].name !== name) continue;
        const open = stack.splice(i)[0];
        if (open.handle) inner.push([open.contentStart, m.index, open.handle]);
        break;
      }
      continue;
    }
    const selfClosing = /\/\s*$/.test(attrs) || VOID.has(name);
    let tagText = m[0];
    for (const [handle, target] of ATTRIBUTE_HANDLES) {
      const key = attr(attrs, handle);
      const value = key && catalog[key]?.[locale];
      if (value) tagText = setAttr(tagText, target, value);
    }
    if (tagText !== m[0]) tags.push([m.index, m.index + m[0].length, tagText]);
    if (RAW.has(name)) {
      const end = html.indexOf(`</${name}>`, token.lastIndex);
      token.lastIndex = end < 0 ? html.length : end + name.length + 3;
      continue;
    }
    if (selfClosing) continue;
    const textKey = attr(attrs, 'data-i18n');
    const htmlKey = attr(attrs, 'data-i18n-html');
    let handle = null;
    if (htmlKey && catalog[htmlKey]?.[locale] != null) handle = catalog[htmlKey][locale];
    else if (textKey && catalog[textKey]?.[locale] != null) handle = escapeText(catalog[textKey][locale]);
    stack.push({ name, contentStart: token.lastIndex, handle });
  }
  const within = (range, other) => other !== range && other[0] <= range[0] && range[1] <= other[1];
  const edits = [
    ...inner.filter((range) => !inner.some((other) => within(range, other))),
    ...tags.filter((range) => !inner.some((other) => other[0] <= range[0] && range[1] <= other[1])),
  ].sort((a, b) => b[0] - a[0]);
  let out = html;
  for (const [start, end, replacement] of edits) out = out.slice(0, start) + replacement + out.slice(end);
  return out;
}

// ── the <head> block ───────────────────────────────────────────────────────

const stripTags = (value) => value.replace(/<[^>]+>/g, '')
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"')
  .replace(/&#(\d+);/g, (w, n) => String.fromCodePoint(Number(n)))
  .replace(/\s+/g, ' ').trim();

/** The FAQ as the page shows it in that language, so the markup never promises an answer the page does not give. */
function faqFrom(html) {
  const start = html.indexOf('id="faq"');
  const end = html.indexOf('id="docs"', start);
  const block = html.slice(start, end);
  return [...block.matchAll(/<h4[^>]*>([\s\S]*?)<\/h4>\s*<p class="lead"[^>]*>([\s\S]*?)<\/p>/g)]
    .map((m) => ({ question: stripTags(m[1]), answer: stripTags(m[2]) }));
}

